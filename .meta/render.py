def _discipline(name):
    for rel in ("assertions/disciplines.yaml", "assertions/imported/disciplines.yaml"):
        for d in (load(rel) or {}).get("disciplines") or []:
            if d["name"] == name:
                return d
    return None


def channel():
    """The channel's verbs, once: `.meta/say/verbs.yaml`."""
    return load("say/verbs.yaml")


def verb_line(program, verb, role=None):
    """How a verb is typed, from the table: the program, `--role` for any Role
    but the channel's default, the verb unless the program is the verb, and
    the shape of its arguments."""
    words = [f".meta/say/{program['name']}"]
    if role and role != "coder":
        words.append(f"--role {role}")
    if verb["name"] != program["name"]:
        words.append(verb["name"])
    if verb.get("usage"):
        words.append(verb["usage"])
    return " ".join(words)


def skill(name, discipline, target, commands, forms=(), role=None):
    """A Discipline, compiled for this harness, and for one Role (solorepo's DR-117).

    A skill is a Discipline plus the commands that carry it out, in the shape one
    harness loads on demand. Everything here is read from the assertions — the
    steps, the judgement, the Articles that enforce it, and any form's own fence.
    Nothing is restated, because a skill that restated the Discipline would be
    the copy nothing checks, and the one an agent actually reads.

    With a Role, the mechanical steps are one line and the Role's verbs, read
    from `verbs.yaml`: the verbs are the steps, each refuses its own misuse,
    and a reading names no verb its Role does not hold. The steps the assertion
    keeps are the ones no verb enforces. Without a Role the reading is the
    whole Discipline's, which is `disciplines.md`'s.

    The paragraphs between those parts are the Discipline's `woven` blocks and
    not this function's (solorepo's DR-152). They hang off the Discipline rather
    than off either page, because one Discipline compiles into a reading per
    Role: asserted on the Artifact each is written to, every one of them would
    be a copy of the last. `{role}` is the only thing a reading adds to one.

    Only the Claude Code target is emitted. The frontmatter an APM primitive
    wants is still unverified (solorepo's DR-040), and writing plausible field names would
    be worse than the gap; this is the same compilation at the scale that can be
    tested today.
    """
    d = _discipline(discipline)
    if d is None:
        return None
    articles = [a for a in ((load("assertions/imported/charter.yaml") or {}).get("articles") or [])
                if a.get("enforces") == d["id"]]
    out = ["---", f"name: {name}", "description: >-"]
    out += ["  " + line for line in textwrap.wrap(authored(target, "description"), 76)]
    out += ["---\n",
            "<!-- Generated by .meta/render.py from assertions/imported/disciplines.yaml.",
            "     Do not edit by hand: edit the assertion and re-render. -->\n",
            f"# {d['name']}\n",
            d["description"].strip() + "\n",
            "## Steps\n"]
    if role:
        table = channel() or {"programs": []}
        out += [woven(d, "verbs", role=role) + "\n"]
        for program in table["programs"]:
            held = [v for v in program["verbs"] if role in v["held_by"]]
            out += [f"- `{verb_line(program, v, role)}` — {v['does']}" for v in held]
        out += ["", woven(d, "steps") + "\n"]
    out += ["\n".join(f"{i}. {s.strip()}" for i, s in enumerate(d["steps"], 1)) + "\n",
            "## Where the judgement is\n",
            d["judgement"].strip() + "\n",
            woven(d, "commands") + "\n",
            "## Commands\n", "```bash", *commands, "```\n"]
    for title, form_name, block in forms:
        out += [f"## {title}\n", woven(d, block) + "\n", "```markdown",
                form(form_name).rstrip("\n"), "```\n"]
    if articles:
        out.append("## What is checked\n")
        for a in articles:
            out.append(f"- **A{a['id'].rsplit('/', 1)[-1]}.** {a['statement'].strip()}")
        out.append("")
    return "\n".join(out)


