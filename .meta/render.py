def _decision_slots():
    """The slot descriptions from the model, which is where the guidance lives.

    Read as plain YAML rather than through a SchemaView so the renderer keeps its
    one dependency, and from every module the class draws slots from — `falsifier`
    is `core`'s, shared with `Article`. The form and the record are two views of the same class, and
    a form whose headings were typed by hand would be the third copy of a shape
    the schema already states.
    """
    slots = {}
    for module in ("work/core.yaml", "work/decisions.yaml"):
        slots.update((load(module) or {}).get("slots") or {})
    return slots


def landed(number):
    """What a Challenge got, rendered from the entries taken under it.

    The account of a finished piece of work is not new prose: every line of it is
    already a `consequence` on some Decision, and writing it again by hand is the
    copy that flatters. So it is generated, and it is **exactly as complete as the
    record** — a decision taken under another change's coat-tails is missing here,
    which is the point rather than a defect.

    Prints rather than writes. It is addressed to a pull request at merge, so it
    goes through the channel that signs: `.meta/say landed 15` runs this for
    every Challenge the body closes and posts each. By hand:

        uvx --with pyyaml python .meta/render.py --landed 11
    """
    challenges = {c["id"]: c for path in
                  sorted((META / "assertions" / "challenges").glob("*.yaml"))
                  for c in (yaml.safe_load(path.read_text()) or {}).get("challenges") or []}
    ident = f"work:challenge/{number}"
    if ident not in challenges:
        return f"No Challenge {ident} is asserted."
    ch = challenges[ident]
    rows = [d for d in record() if d.get("challenge") == ident]
    out = [f"## What landed for #{number} — {ch['name']}\n"]
    if not rows:
        out.append("No decision names this Challenge.\n")
        return "\n".join(out)
    out.append(f"{len(rows)} decisions, and what each of them changed. Generated from the\n"
               f"record: an entry missing here was taken without one.\n")
    for d in rows:
        num = d["id"].rsplit("/", 1)[-1]
        head = f"**[DR-{num}]({RECORD.format(num)}) · {d['name'].split(' · ', 1)[-1]}**"
        if d.get("status") != "ADOPTED":
            head += f" — {d['status'].lower()}"
        out.append(head + "\n")
        out += [f"- {c.strip()}" for c in (d.get("consequences") or
                                           ["No consequences recorded."])]
        out.append("")
    return "\n".join(out)


def decisions():
    """The index to the record, and the only thing rendered from it (DR-082).

    An entry is its assertion file, so rendering one as markdown made a second
    copy and nothing else. What survives is what a directory listing cannot do:
    map a number to the question it settled, so a reader can choose an entry
    without opening any, and invert `enacted_in` into the **By artifact** table,
    which is the only answer to "which decisions account for this file".

    Deliberately insufficient to apply anything, per Progressive Disclosure. A
    withdrawn entry is listed under Holes rather than in the record, and keeps
    its number, because a citation to a hole must still resolve.
    """
    rows = record()
    if not rows:
        return None
    structure = load("assertions/structure.yaml") or {}
    levels = {u["id"]: u["name"] for key in ("products", "projects")
              for u in structure.get(key) or []}
    out = [BANNER.format(src="assertions/decisions/"),
           "## Decision record\n",
           "_Every decision taken, with why. Newest last._\n",
           "Add an entry when the question is settled, not when the answer is built —\n"
           "`status` says how far it has got. A number is a\n"
           "**stable identifier** and is never reused: an entry that turned out to record a\n"
           "narrative rather than a foreclosure is withdrawn, and its number stays a hole\n"
           "at the foot of this page.\n",
           "**This page routes and does not restate.** An entry *is* its assertion file,\n"
           "named for its number, so a conversation reaches one as\n"
           "`@.meta/assertions/decisions/DR-011.yaml`. The line here says an entry exists\n"
           "and what question it answered; only the entry is sufficient to apply it.\n",
           "| Entry | The question it settled | Status |",
           "| :-- | :-- | :-- |"]
    paths = artifacts()
    holes = []
    for d in rows:
        num = d["id"].rsplit("/", 1)[-1]
        if d.get("status") == "WITHDRAWN":
            holes.append(d)
            continue
        status = (d.get("status") or "").capitalize()
        if d.get("status") == "SUPERSEDED":
            status = f"Superseded by {_link(rows, d['superseded_by'])}"
        title = d["name"].split(" · ", 1)[-1]
        # The level, where it is not the Portfolio's (DR-093).
        for level in ("product", "project"):
            if d.get(level):
                title += f" · {levels.get(d[level], d[level])}"
        out.append(f"| [DR-{num}]({ENTRY.format(num)}) | {title} | {status} |")
    out.append("")
    if holes:
        out.append("## Holes\n")
        out.append("Numbers that were issued and are not decisions. They are never reused, and\n"
                   "the prose is kept: a paragraph that was worth writing does not stop being\n"
                   "true because it turned out to foreclose nothing.\n")
        for d in holes:
            num = d["id"].rsplit("/", 1)[-1]
            why = " ".join(d["withdrawn_because"].strip().split())
            out.append(f"- [DR-{num}]({ENTRY.format(num)}) — withdrawn. "
                       + why.split(". ")[0].rstrip(".") + ".")
        out.append("")
    by_artifact = {}
    for d in rows:
        for ref in (d.get("enacted_in") or []):
            by_artifact.setdefault(paths.get(ref, ref), []).append(
                d["id"].rsplit("/", 1)[-1])
    if by_artifact:
        out.append("## By artifact\n")
        out.append("Which entries account for a file. The other direction of `enacted_in`,\n"
                   "and the query a reader in a file actually has.\n")
        out.append("| Artifact | Entries |")
        out.append("| :-- | :-- |")
        for path in sorted(by_artifact):
            nums = ", ".join(f"[DR-{n}]({ENTRY.format(n)})"
                             for n in sorted(by_artifact[path]))
            out.append(f"| [`{path}`]({posixpath.relpath(path, '.meta')}) | {nums} |")
        out.append("")
    return "\n".join(out)


def _link(rows, ident):
    """A supersession, rendered as a link to the entry it names."""
    for d in rows:
        if d["id"] == ident:
            return f"[{d['name'].split(' · ')[0]}]({ENTRY.format(d['id'].rsplit('/', 1)[-1])})"
    return ident


def decision_form():
    """The form for an entry, rendered from the same class the record uses.

    One class at three levels — the Portfolio's, a Product's, a Project's —
    told apart by what the entry names (DR-059, DR-093), so the form's headings
    are the model's slots and its guidance is their descriptions. Typing them
    here as well would be the copy that disagrees — and the copy that keeps a
    form asking for something the model stopped requiring.
    """
    slots = _decision_slots()
    if not slots:
        return None

    def guidance(name):
        return " ".join(slots[name]["description"].split())

    out = [BANNER.format(src="work/decisions.yaml"),
           "# DR-<nnn> · <one-line title, present tense>\n",
           "**Not authoritative.** The Charter and the Disciplines hold the rules and win\n"
           "any disagreement. This records why something is built the way it is, at the\n"
           "level whose readers share the matter: the Portfolio's, a Product's or a\n"
           "Project's. One class and one record, `.meta/assertions/decisions/`, whatever\n"
           "the level — the entry names its Product or Project, or neither.\n",
           "- **Status:** <" + " | ".join(
               (load("work/decisions.yaml") or {})["enums"]["DecisionStatus"]["permissible_values"]) + ">",
           "- **Level:** <Portfolio | Product: which | Project: which>\n",
           "## Context\n", "<" + guidance("context") + ">\n",
           "## Decision\n",
           "<What was decided, in the present tense — \"we do X\". One paragraph.>\n",
           "## Alternatives considered\n",
           "<" + guidance("alternatives") + ">\n",
           "### A: <alternative> — rejected\n", "<" + guidance("reason") + ">\n",
           "### B: <alternative> — chosen\n", "<As above, including what it costs.>\n",
           "## Consequences\n", "<" + guidance("consequences") + ">\n",
           "## What would falsify this\n", "<" + guidance("falsifier") + ">\n",
           "## Bearing on the Charter\n",
           "Dereference every citation per A12 — \"A9 — a seed is data, gated by "
           "rendering it\"\nrather than a bare \"A9\". Omit the section if there is "
           "none.\n",
           "- **Applies:** <" + guidance("applies") + ">",
           "- **Departs from:** <" + guidance("departs_from") + ">\n",
           "## Supersedes\n",
           "<" + guidance("supersedes") + " Omit the section if there is none.>\n"]
    return "\n".join(out)


def _discipline(name):
    for rel in ("assertions/disciplines.yaml", "assertions/imported/disciplines.yaml"):
        for d in (load(rel) or {}).get("disciplines") or []:
            if d["name"] == name:
                return d
    return None


def skill(name, discipline, trigger, commands, forms=()):
    """A Discipline, compiled for this harness.

    A skill is a Discipline plus the commands that carry it out, in the shape one
    harness loads on demand. Everything here is read from the assertions — the
    steps, the judgement, the Articles that enforce it, and any form's own fence.
    Nothing is restated, because a skill that restated the Discipline would be
    the copy nothing checks, and the one an agent actually reads.

    Only the Claude Code target is emitted. The frontmatter an APM primitive
    wants is still unverified (DR-040), and writing plausible field names would
    be worse than the gap; this is the same compilation at the scale that can be
    tested today.
    """
    d = _discipline(discipline)
    if d is None:
        return None
    articles = [a for a in ((load("assertions/imported/charter.yaml") or {}).get("articles") or [])
                if a.get("enforces") == d["id"]]
    out = ["---", f"name: {name}", "description: >-"]
    out += ["  " + line for line in trigger]
    out += ["---\n",
            "<!-- Generated by .meta/render.py from assertions/imported/disciplines.yaml.",
            "     Do not edit by hand: edit the assertion and re-render. -->\n",
            f"# {d['name']}\n",
            d["description"].strip() + "\n",
            "## Steps\n",
            "\n".join(f"{i}. {s.strip()}" for i, s in enumerate(d["steps"], 1)) + "\n",
            "## Where the judgement is\n",
            d["judgement"].strip() + "\n",
            "**None of the below decides any of the above.** A script can tell you a thread",
            "is unanswered, or a branch unpushed. What to write, and whether a point is",
            "right, is yours.\n",
            "## Commands\n", "```bash", *commands, "```\n"]
    for title, form_name, note in forms:
        out += [f"## {title}\n", note + "\n", "```markdown",
                form(form_name).rstrip("\n"), "```\n"]
    if articles:
        out.append("## What is checked\n")
        for a in articles:
            out.append(f"- **A{a['id'].rsplit('/', 1)[-1]}.** {a['statement'].strip()}")
        out.append("")
    return "\n".join(out)


