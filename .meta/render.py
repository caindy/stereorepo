def rendered():
    """Every generated path, relative to `.meta/`, mapped to its content.

    A target renders one file or a set of them. Both callers — the writer below
    and `check.py`'s staleness check — want the flat mapping, so the fan-out is
    resolved once here rather than in each of them.

    Counts are filled last, over every page alike: a sentence citing one is
    prose in the assertions, and which generator carries it to a page is not
    that sentence's business.
    """
    out = {}
    for name, fn in TARGETS.items():
        result = fn()
        if result is None:
            continue
        out.update(result if isinstance(result, dict) else {name: result})
    return {name: counted(text) for name, text in out.items()}


def unrendered():
    """Targets that produce nothing and yet have a file on disk, by name.

    By name and not as a sentence about the name, because both callers key on
    the page: the gate wraps it in prose, and `check_pr.py` asks whether the
    record's index is one of them. A sentence answered that question `False`
    however the page stood.
    """
    return [name for name, fn in TARGETS.items()
            if fn() is None and (META / name).exists()]


