def python_bootstrap_instructions() -> str:
    """Generates bootstraps/python/.apm/instructions/python-standard.instructions.md per solorepo's DR-208.

    `applyTo` is every `*.py`, which in a portfolio is two kinds of file and not
    one: inherited tooling under `.meta/` and the Projects the assertions declare.
    They take different configuration and different gates, so guidance that named
    only one of them named the wrong one for every `.meta/` file it reached
    (solorepo's DR-212).
    """
    return (
        "---\n"
        "description: Python standard conventions and development guidance across solorepo\n"
        'applyTo: "**/*.py"\n'
        "---\n\n"
        "<!-- Generated by .meta/apm_compile.py from bootstraps/python/README.md. Do not edit by hand:\n"
        "     edit the assertions and re-render. -->\n\n"
        "# Python Standard Guidance\n\n"
        "A portfolio holds two kinds of Python target. Settle which one a file belongs to\n"
        "before running any checker over it; `assertions/structure.yaml` is what settles it,\n"
        "since every Project declares the `gate:` that holds it and a Project is instantiated\n"
        "wherever it was asked for.\n\n"
        "**Repository tooling — `.meta/`.** Inherited by every portfolio. Configured by\n"
        "`.meta/ruff.toml` and `.meta/mypy.ini`, run through `python3` and `uvx`, verified by\n"
        "`just gate meta`. It has no `pyproject.toml`, no `[dependency-groups]` and no\n"
        "`tests/`; its behavioural tests are the probes under `.meta/checks/probes/`. Never\n"
        "create a `pyproject.toml` at the repository root, and never delete an import\n"
        "carrying `# noqa: F401  # reason: ...` — it registers gate steps.\n\n"
        "**A Project workspace.** Owns its `pyproject.toml` and its dependency groups, and is\n"
        "verified by `uv run gate` typed in its own directory. It must satisfy the six\n"
        "project-level disciplines: Literate Programming, Ratchet, Observed Failure, Nothing\n"
        "Unconsumed, Seeded Artifacts, and Written Decisions.\n\n"
        "Give every checker its target's configuration by name; a bare `ruff check .` or\n"
        "`mypy .` at the repository root sweeps both targets under one configuration, which is\n"
        "right for neither. The sixteen skills in this package carry the rest, and\n"
        "`py-quality-setup` holds the contract in full.\n"
    )


def python_bootstrap_primitives(root_dir: pathlib.Path = ROOT) -> dict[str, str | bytes]:
    """Compiles bootstraps/python/ assertions and skills into APM primitives (solorepo's DR-208).

    A skill file that is not UTF-8 text — a diagram beside its markdown, a
    stray `__pycache__/*.pyc` left by importing a skill's script — is copied
    as bytes rather than decoded, named on stderr so the compile still says
    what it carried rather than only reporting how many primitives it wrote.
    """
    py_dir = root_dir / "bootstraps" / "python"
    if not py_dir.is_dir():
        return {}
    out: dict[str, str | bytes] = {}
    out["../bootstraps/python/apm.yml"] = python_bootstrap_manifest()
    out["../bootstraps/python/.apm/instructions/python-standard.instructions.md"] = python_bootstrap_instructions()

    skills_dir = py_dir / "skills"
    if skills_dir.is_dir():
        for item in sorted(skills_dir.rglob("*")):
            if not item.is_file():
                continue
            rel_within_skills = item.relative_to(skills_dir)
            if len(rel_within_skills.parts) >= 2:
                rel_path = f"../bootstraps/python/.apm/skills/{rel_within_skills}"
                raw = item.read_bytes()
                try:
                    out[rel_path] = raw.decode("utf-8")
                except UnicodeDecodeError:
                    print(f"apm_compile: {item.relative_to(root_dir)} is not UTF-8 text; "
                          "copying as bytes", file=sys.stderr)
                    out[rel_path] = raw

    return out


def rendered_primitives(meta_dir: pathlib.Path = META) -> dict[str, str | bytes]:
    """All generated APM primitive paths relative to .meta/, mapped to content."""
    primitives: dict[str, str | bytes] = {}
    primitives["apm.yml"] = apm_manifest()
    primitives[".apm/instructions/ubiquitous-language.instructions.md"] = ubiquitous_language_instructions(meta_dir)
    primitives.update(discipline_instructions(meta_dir))
    primitives.update(agent_primitives(meta_dir))
    primitives.update(skill_primitives(meta_dir))
    primitives.update(hook_primitives())
    primitives.update(python_bootstrap_primitives(meta_dir.parent))
    return primitives


def check_root_symlinks(root_dir: pathlib.Path = ROOT) -> list[str]:
    """Checks that root harness documentation symlinks point to AGENTS.md (solorepo's DR-172)."""
    problems = []
    agents_md = root_dir / "AGENTS.md"
    claude_md = root_dir / "CLAUDE.md"
    gemini_md = root_dir / "GEMINI.md"

    if not agents_md.is_file():
        problems.append("AGENTS.md is missing from repository root")
        return problems

    for link_path in (claude_md, gemini_md):
        if not link_path.is_symlink():
            problems.append(f"{link_path.name} is not a symlink to AGENTS.md")
        else:
            try:
                target = link_path.resolve()
                if target != agents_md.resolve():
                    problems.append(f"{link_path.name} resolves to {target}, expected {agents_md}")
            except Exception as e:
                problems.append(f"{link_path.name} broken symlink: {e}")

    return problems


def reconcile_root(root_dir: pathlib.Path = ROOT) -> list[str]:
    """Reconciles harness root files ensuring AGENTS.md single-source invariance (solorepo's DR-172).

    `CLAUDE.md` and `GEMINI.md` are symlinks to `AGENTS.md` and this restores
    them as such, including where one has been replaced by a regular file: an
    external compiler that writes its own copy is the way that happens, and a
    copy is the drift the symlink exists to rule out.
    """
    actions = []
    agents_md = root_dir / "AGENTS.md"
    claude_md = root_dir / "CLAUDE.md"
    gemini_md = root_dir / "GEMINI.md"

    if not agents_md.is_file():
        actions.append("ERROR: AGENTS.md is missing from repository root")
        return actions

    for link_path in (claude_md, gemini_md):
        if link_path.is_symlink():
            target = link_path.resolve()
            if target != agents_md.resolve():
                link_path.unlink()
                link_path.symlink_to("AGENTS.md")
                actions.append(f"Fixed symlink {link_path.name} -> AGENTS.md")
        elif link_path.exists():
            link_path.unlink()
            link_path.symlink_to("AGENTS.md")
            actions.append(f"Restored symlink {link_path.name} -> AGENTS.md from file")
        else:
            link_path.symlink_to("AGENTS.md")
            actions.append(f"Created symlink {link_path.name} -> AGENTS.md")

    meta_path = root_dir / ".meta"
    if not meta_path.is_dir():
        meta_path = META
    actions.extend(reconcile_harnesses(meta_path, root_dir))

    return actions


def reconcile_harnesses(meta_dir: pathlib.Path = META, root_dir: pathlib.Path = ROOT) -> list[str]:
    """Projects single-source APM cognitive assets to multi-harness target directories (solorepo's DR-172, solorepo's DR-201, solorepo's #430).

    When Microsoft APM CLI is present, invokes `apm install ./.meta --target antigravity,codex,gemini`
    to deploy skills, agents, and hooks into `.agents/`, `.gemini/`, and `.codex/`.
    When APM CLI is absent, projects `.meta/.apm/skills/` into `.agents/skills/` directly.
    """
    actions = []
    apm_bin = shutil.which("apm")
    if apm_bin:
        res = subprocess.run(
            [apm_bin, "install", "./.meta", "--target", "antigravity,codex,gemini"],
            cwd=str(root_dir),
            capture_output=True,
            text=True,
        )
        if res.returncode == 0:
            actions.append("Materialized multi-harness cognitive assets via APM CLI (.agents/, .gemini/, .codex/)")
            return actions

    src_skills = meta_dir / ".apm" / "skills"
    dest_skills = root_dir / ".agents" / "skills"
    if src_skills.is_dir():
        dest_skills.mkdir(parents=True, exist_ok=True)
        for item in sorted(src_skills.iterdir()):
            if not item.is_dir():
                continue
            dest_skill_dir = dest_skills / item.name
            dest_skill_dir.mkdir(parents=True, exist_ok=True)
            for skill_file in item.iterdir():
                if skill_file.is_file():
                    target_file = dest_skill_dir / skill_file.name
                    target_file.write_bytes(skill_file.read_bytes())
        actions.append("Projected skills from .meta/.apm/skills/ into .agents/skills/")

    return actions


def write_primitives(meta_dir: pathlib.Path = META, root_dir: pathlib.Path = ROOT) -> int:
    """Writes all compiled APM primitives to .meta/.apm/ and reconciles root files."""
    prims = rendered_primitives(meta_dir)
    for rel_path, content in prims.items():
        full_path = meta_dir / rel_path
        full_path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            full_path.write_bytes(content)
        else:
            full_path.write_text(content, encoding="utf-8")

    reconcile_root(root_dir)
    return len(prims)


def check_primitives(meta_dir: pathlib.Path = META, root_dir: pathlib.Path = ROOT) -> list[str]:
    """Checks that on-disk APM primitives match compiled output without drift."""
    stale = []
    prims = rendered_primitives(meta_dir)
    for rel_path, content in prims.items():
        full_path = meta_dir / rel_path
        if not full_path.is_file():
            stale.append(f"{rel_path} is missing")
        elif isinstance(content, bytes):
            if full_path.read_bytes() != content:
                stale.append(f"{rel_path} has drifted from assertions")
        elif full_path.read_text(encoding="utf-8") != content:
            stale.append(f"{rel_path} has drifted from assertions")

    stale.extend(check_root_symlinks(root_dir))
    return stale


def run_apm(args: list[str], meta_dir: pathlib.Path = META) -> int:
    """Runs the apm CLI inside meta_dir, passing args (solorepo's DR-201)."""
    apm_bin = shutil.which("apm")
    if not apm_bin:
        print(
            "apm is not installed. Install via 'brew install apm' or "
            "'curl -sSL https://aka.ms/apm-unix | sh'",
            file=sys.stderr,
        )
        return 1
    res = subprocess.run([apm_bin, *args], cwd=str(meta_dir))
    return res.returncode


def validate_apm(meta_dir: pathlib.Path = META, root_dir: pathlib.Path = ROOT) -> int:
    """Validates APM primitives against LinkML assertions and APM CLI schema (solorepo's DR-201, solorepo's DR-208)."""
    stale = check_primitives(meta_dir, root_dir)
    if stale:
        print("Internal assertion-to-primitive drift detected:", file=sys.stderr)
        for item in stale:
            print(f"  {item}", file=sys.stderr)
        return 1
    print("Internal assertion-to-primitive projection is up to date.")
    apm_bin = shutil.which("apm")
    if not apm_bin:
        print("Note: apm CLI is not installed; skipping downstream APM engine validation.")
        return 0
    code = run_apm(["compile", "--validate"], meta_dir=meta_dir)
    if code != 0:
        return code
    py_dir = root_dir / "bootstraps" / "python"
    if py_dir.is_dir() and (py_dir / "apm.yml").is_file():
        code = run_apm(["compile", "--validate"], meta_dir=py_dir)
    return code


def pack_apm(args: list[str], meta_dir: pathlib.Path = META) -> int:
    """Packs the APM project into distributable plugin/bundle artifacts (solorepo's DR-201)."""
    return run_apm(["pack", *args], meta_dir=meta_dir)


def compile_apm(args: list[str], meta_dir: pathlib.Path = META) -> int:
    """Compiles the APM project into target harness directories redirected to root (solorepo's DR-172, solorepo's DR-201)."""
    cmd_args = ["compile", "--root", ".."]
    if not any(a.startswith("-t") or a.startswith("--target") or a == "--all" for a in args):
        cmd_args.extend(["-t", "claude,gemini,copilot"])
    cmd_args.extend(args)
    return run_apm(cmd_args, meta_dir=meta_dir)


def main() -> None:
    """CLI entrypoint for APM compiler, packaging, and root reconciliation (solorepo's DR-201)."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated primitives are stale")
    parser.add_argument("--reconcile", action="store_true", help="Reconcile harness root symlinks only")
    parser.add_argument(
        "command",
        nargs="?",
        choices=["validate", "pack", "compile", "audit", "doctor", "preview"],
        help="APM operation to perform",
    )
    parser.add_argument("extra_args", nargs=argparse.REMAINDER, help="Additional arguments forwarded to apm")
    args = parser.parse_args()

    if args.reconcile:
        actions = reconcile_root()
        if actions:
            print("\n".join(actions))
        else:
            print("Harness root documentation symlinks are intact.")
        sys.exit(0)

    if args.check:
        stale = check_primitives()
        if stale:
            print("APM primitives are stale:")
            for item in stale:
                print(f"  {item}")
            sys.exit(1)
        print("APM primitives are up to date.")
        sys.exit(0)

    if args.command == "validate":
        sys.exit(validate_apm())
    elif args.command == "pack":
        sys.exit(pack_apm(args.extra_args))
    elif args.command == "compile":
        sys.exit(compile_apm(args.extra_args))
    elif args.command in ("audit", "doctor", "preview"):
        sys.exit(run_apm([args.command, *args.extra_args]))

    count = write_primitives()
    print(f"Compiled {count} APM primitives.")


if __name__ == "__main__":
    main()
